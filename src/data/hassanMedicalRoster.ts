function createSlots(
  docKey: string,
  todayTimes: { time: string; emergency?: boolean; booked?: boolean }[],
  tomorrowTimes: { time: string; emergency?: boolean }[]
): DoctorSlot[] {
  const slots: DoctorSlot[] = [];
  todayTimes.forEach((entry, idx) => {
    slots.push({
      id: `${docKey}-today-${idx}`,
      dayLabel: 'Today',
      timeLabel: entry.time,
      isoSlotKey: `today-${entry.time.replace(/\s+/g, '')}`,
      isEmergencySlot: Boolean(entry.emergency),
      isBooked: Boolean(entry.booked),
    });
  });
  tomorrowTimes.forEach((entry, idx) => {
    slots.push({
      id: `${docKey}-tmrw-${idx}`,
      dayLabel: 'Tomorrow',
      timeLabel: entry.time,
      isoSlotKey: `tomorrow-${entry.time.replace(/\s+/g, '')}`,
      isEmergencySlot: Boolean(entry.emergency),
      isBooked: false,
    });
  });
  return slots;
}

